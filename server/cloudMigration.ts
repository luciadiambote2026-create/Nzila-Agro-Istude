import fs from 'node:fs';
import path from 'node:path';
import { db } from './db.ts';

export interface CloudMigrationTableSummary {
  tableName: string;
  rowCount: number;
}

export interface CloudMigrationStatus {
  currentEngine: string;
  targetEngine: string;
  sqliteFileSizeBytes: number;
  totalTables: number;
  totalRows: number;
  hasDatabaseUrlEnv: boolean;
  tables: CloudMigrationTableSummary[];
  checklist: Array<{
    key: string;
    label: string;
    ready: boolean;
    detail: string;
  }>;
}

function getUserTableNames(): string[] {
  const rows = db
    .prepare(
      `SELECT name FROM sqlite_master
       WHERE type = 'table' AND name NOT LIKE 'sqlite_%'
       ORDER BY name ASC`
    )
    .all() as Array<{ name: string }>;
  return rows.map((r) => String(r.name));
}

function mapSqliteTypeToPostgres(sqliteType: string, isAutoIncrementPk: boolean): string {
  if (isAutoIncrementPk) return 'BIGINT GENERATED BY DEFAULT AS IDENTITY';
  const upper = (sqliteType || 'TEXT').toUpperCase();
  if (upper.includes('INT')) return 'BIGINT';
  if (upper.includes('REAL') || upper.includes('FLOA') || upper.includes('DOUB')) return 'DOUBLE PRECISION';
  if (upper.includes('BLOB')) return 'BYTEA';
  return 'TEXT';
}

function escapePgLiteral(val: unknown): string {
  if (val === null || val === undefined) return 'NULL';
  if (typeof val === 'number') {
    return Number.isFinite(val) ? String(val) : 'NULL';
  }
  if (typeof val === 'boolean') {
    return val ? '1' : '0';
  }
  const str = String(val).replace(/'/g, "''");
  return `'${str}'`;
}

export function getCloudMigrationStatus(): CloudMigrationStatus {
  const dbPath = path.resolve(process.cwd(), 'data', 'nzila-agro.sqlite');
  let sqliteFileSizeBytes = 0;
  try {
    sqliteFileSizeBytes = fs.statSync(dbPath).size;
  } catch {
    sqliteFileSizeBytes = 0;
  }

  const tableNames = getUserTableNames();
  const tables: CloudMigrationTableSummary[] = [];
  let totalRows = 0;

  for (const tableName of tableNames) {
    const countRow = db.prepare(`SELECT COUNT(*) as count FROM "${tableName}"`).get() as { count: number };
    const rowCount = Number(countRow?.count || 0);
    totalRows += rowCount;
    tables.push({ tableName, rowCount });
  }

  const hasAppUrl = Boolean(process.env.APP_URL && process.env.APP_URL.startsWith('https://'));

  return {
    currentEngine: 'SQLite (Local WAL)',
    targetEngine: 'PostgreSQL 16 / Google Cloud SQL',
    sqliteFileSizeBytes,
    totalTables: tables.length,
    totalRows,
    hasDatabaseUrlEnv: false,
    tables,
    checklist: [
      {
        key: 'local_mode',
        label: 'Modo Local SQLite ativo para testes imediatos (sem chaves externas)',
        ready: true,
        detail: 'A plataforma funciona integralmente com SQLite local e referências Multicaixa padrão. As credenciais de nuvem podem ser configuradas mais tarde.',
      },
      {
        key: 'schema_export',
        label: 'Exportador DDL + Dados compatível com PostgreSQL / Cloud SQL',
        ready: true,
        detail: `${tables.length} tabelas e ${totalRows} registos prontos para exportação em .sql transacional quando decidir migrar.`,
      },
      {
        key: 'https_domain',
        label: 'URL pública HTTPS (APP_URL)',
        ready: hasAppUrl,
        detail: hasAppUrl
          ? `Ligado em ${process.env.APP_URL}`
          : 'Opcional em ambiente local; configure um domínio HTTPS quando publicar em produção.',
      },
    ],
  };
}

export function buildPostgresMigrationSql(): { filename: string; sql: string; tablesCount: number; rowsCount: number } {
  const tableNames = getUserTableNames();
  const lines: string[] = [
    '-- ============================================================================',
    '-- Nzila Agro — Script de Migração para PostgreSQL / Google Cloud SQL',
    `-- Gerado em (UTC): ${new Date().toISOString()}`,
    '-- Como importar: psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f <ficheiro.sql>',
    '-- ============================================================================',
    '',
    'BEGIN;',
    '',
  ];

  let totalRows = 0;

  for (const tableName of tableNames) {
    const columns = db.prepare(`PRAGMA table_info("${tableName}")`).all() as Array<{
      cid: number;
      name: string;
      type: string;
      notnull: number;
      dflt_value: string | null;
      pk: number;
    }>;

    const pkColumns = columns.filter((c) => c.pk > 0);
    const singleIntPk =
      pkColumns.length === 1 && (pkColumns[0].type || '').toUpperCase().includes('INT');

    const colDefs = columns.map((col) => {
      const isAutoPk = singleIntPk && col.pk === 1;
      const pgType = mapSqliteTypeToPostgres(col.type, isAutoPk);
      const parts = [`  "${col.name}" ${pgType}`];
      if (col.pk === 1 && pkColumns.length === 1) {
        parts.push('PRIMARY KEY');
      }
      if (col.notnull === 1 && !isAutoPk) {
        parts.push('NOT NULL');
      }
      if (col.dflt_value !== null && !isAutoPk) {
        const dflt = String(col.dflt_value).trim();
        if (dflt.toLowerCase() === "(datetime('now'))") {
          parts.push('DEFAULT CURRENT_TIMESTAMP');
        } else {
          parts.push(`DEFAULT ${dflt}`);
        }
      }
      return parts.join(' ');
    });

    if (pkColumns.length > 1) {
      const pkList = pkColumns.map((c) => `"${c.name}"`).join(', ');
      colDefs.push(`  PRIMARY KEY (${pkList})`);
    }

    lines.push(`-- Tabela: ${tableName}`);
    lines.push(`CREATE TABLE IF NOT EXISTS "${tableName}" (`);
    lines.push(colDefs.join(',\n'));
    lines.push(');');
    lines.push('');

    const rows = db.prepare(`SELECT * FROM "${tableName}"`).all() as Array<Record<string, unknown>>;
    if (rows.length > 0) {
      const colNames = columns.map((c) => c.name);
      const quotedCols = colNames.map((c) => `"${c}"`).join(', ');
      for (const row of rows) {
        const vals = colNames.map((col) => escapePgLiteral(row[col])).join(', ');
        lines.push(`INSERT INTO "${tableName}" (${quotedCols}) VALUES (${vals}) ON CONFLICT DO NOTHING;`);
        totalRows += 1;
      }
      if (singleIntPk) {
        const pkCol = pkColumns[0].name;
        lines.push(
          `SELECT setval(pg_get_serial_sequence('"${tableName}"', '${pkCol}'), COALESCE((SELECT MAX("${pkCol}") FROM "${tableName}"), 1), true);`
        );
      }
      lines.push('');
    }
  }

  lines.push('COMMIT;');
  lines.push('');

  const dateTag = new Date().toISOString().slice(0, 10);
  return {
    filename: `nzila-agro-postgres-migration-${dateTag}.sql`,
    sql: lines.join('\n'),
    tablesCount: tableNames.length,
    rowsCount: totalRows,
  };
}
